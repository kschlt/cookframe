/**
 * A recipe's picture of the dish, as the running instance serves it.
 *
 * Each `describe` string is the proof id it satisfies. Every proof here asks the
 * COMPOSED instance (`composeInstance`, through `testInstanceDeps`), because the
 * claim is about what an operator's library shows, not about what the renderer
 * would show if somebody called it with a resolver.
 *
 * Four claims:
 *
 *  1. A recipe that has a picture shows it, on its page, on its library card and
 *     on the page the cooking address degrades to, and the address those pages
 *     name answers with the bytes the store holds.
 *  2. What that answer says the bytes are follows from the bytes alone. A stored
 *     file carries no label, and the one the publisher sent is that publisher's
 *     claim; bytes that are none of JPEG, PNG and WebP are not served at all,
 *     because a guessed type is how an HTML or SVG document stored as a
 *     "picture" would run as a page on this instance's origin.
 *  3. The address is the library's: without the library credential, and for
 *     every recipe with nothing to show, it is the one shared not-found answer.
 *  4. A recipe without a picture says so, in a sentence that is true for its
 *     source: a photographed cookbook page is not a picture of the dish
 *     (ontology §7), so its page says the photograph is the source, not that
 *     nothing was kept.
 *
 * No proof brings a picture from anywhere. Every image here is generated by
 * this file, a few bytes long, and is nobody's photograph.
 */
