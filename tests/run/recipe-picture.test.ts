import { html } from "hono/html"
import { describe, expect, it } from "vitest"
import { CanonicalRecipe, SourceSnapshot } from "../../schema/index.js"
import { servedImageType } from "../../src/http/image-signature.js"
import { NOT_FOUND_BODY } from "../../src/http/not-found.js"
import { NO_PICTURE_OF_THE_DISH } from "../../src/render/recipe-page.js"
import { composeInstance } from "../../src/server/instance.js"
import type { ByteStore } from "../../src/storage/index.js"
